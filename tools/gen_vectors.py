# gen_vectors.py - tests/vectors.txt (tools/bntref, Rust argon2 0.5 = blocknet core) -> src/bnt_vectors.h
import sys
rows = [l.split() for l in open('tests/vectors.txt') if l.strip()]
o = ['// bnt_vectors.h - generated by tools/gen_vectors.py from tests/vectors.txt.',
     '// Reference hashes of the Rust argon2 0.5 crate, called exactly like blocknet core',
     '// (Argon2id v0x13, t=1, p=1, out 32, password = nonce LE, salt = 100-byte header), for',
     '// several memory sizes m (KiB); m = 2097152 is the real Blocknet PoW.',
     '#pragma once', '#include <stdint.h>', 'struct BntVector { uint32_t m; const char* header_hex; uint64_t nonce; const char* hash_hex; };',
     'static const BntVector bnt_vectors[] = {']
for m, h, n, x in rows:
    o.append('    { %su, "%s", %suLL, "%s" },' % (m, h, n, x))
o.append('};')
open('src/bnt_vectors.h', 'w').write('\n'.join(o) + '\n')
print(len(rows), 'vectors')
